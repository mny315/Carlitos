package io.github.mny315.carlitos

import android.app.Activity
import android.app.Instrumentation
import android.content.Intent
import android.graphics.BitmapFactory
import android.os.SystemClock
import androidx.media3.common.util.UnstableApi
import com.google.zxing.BinaryBitmap
import com.google.zxing.MultiFormatReader
import com.google.zxing.RGBLuminanceSource
import com.google.zxing.client.android.Intents
import com.google.zxing.common.HybridBinarizer
import com.google.zxing.integration.android.IntentIntegrator
import java.io.File

/** Runs against a real desktop peer; uses only the isolated playbacktest app. */
@UnstableApi
internal class SyncSuite(private val instrumentation: Instrumentation) {
    fun run() {
        check(instrumentation.targetContext.packageName.endsWith(".playbacktest"))
        val activity = instrumentation.startActivitySync(Intent(instrumentation.targetContext, MainActivity::class.java)
            .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)) as MainActivity
        val directory = File(instrumentation.targetContext.filesDir, "sync")
        val suite = PlaybackSuite(instrumentation)
        suite.call("sync_prepare", "path" to File(directory, "book.wav").absolutePath)
        UiSuite(instrumentation).syncAppearanceChecks()
        // Decode the exact PNG generated by Carlitos's Rust QR renderer, then
        // pass through the same Activity result callback as the camera scanner.
        val bitmap = checkNotNull(BitmapFactory.decodeFile(File(directory, "pair.png").absolutePath))
        val pixels = IntArray(bitmap.width * bitmap.height)
        bitmap.getPixels(pixels, 0, bitmap.width, 0, 0, bitmap.width, bitmap.height)
        val code = MultiFormatReader().decode(BinaryBitmap(HybridBinarizer(RGBLuminanceSource(bitmap.width, bitmap.height, pixels)))).text
        bitmap.recycle()
        check(code.startsWith("CARLITOS://PAIR/2/"))
        instrumentation.runOnMainSync {
            MainActivity::class.java.getDeclaredMethod("onActivityResult", Int::class.javaPrimitiveType,
                Int::class.javaPrimitiveType, Intent::class.java).apply { isAccessible = true }
                .invoke(activity, IntentIntegrator.REQUEST_CODE, Activity.RESULT_OK,
                    Intent().putExtra(Intents.Scan.RESULT, code).putExtra(Intents.Scan.RESULT_FORMAT, "QR_CODE"))
        }
        val deadline = SystemClock.elapsedRealtime() + 30000
        var synchronized = false
        while (SystemClock.elapsedRealtime() < deadline) {
            val progress = suite.call("state").getJSONArray("progress")
            if (progress.length() == 1 && progress.getJSONObject(0).getLong("position") == 90000L) {
                synchronized = true
                break
            }
            Thread.sleep(100)
        }
        check(synchronized) { "Desktop progress did not reach Android: ${suite.call("state")}" }
        suite.note("Rust QR decoded by Android and desktop position received over Wi-Fi")
        UiSuite(instrumentation).apply {
            call("appearance", "theme" to 0, "language" to 2)
            eventually("Paired device shown") { call().getInt("sync_peers") == 1 }
            scrollSyncTo("Sync")
            capture("sync-connected")
            syncButtonChecks()
        }
        val rateDeadline = SystemClock.elapsedRealtime() + 10000
        while (suite.call("state").getJSONArray("book_rates").length() == 0 && SystemClock.elapsedRealtime() < rateDeadline) Thread.sleep(50)
        check(suite.call("state").getJSONArray("book_rates").getJSONObject(0).getDouble("value") == 1.75)
        suite.call("sync_open")
        val openDeadline = SystemClock.elapsedRealtime() + 10000
        while (suite.call("state").getJSONObject("playback").getString("phase") != "Ready" && SystemClock.elapsedRealtime() < openDeadline) Thread.sleep(50)
        val opened = suite.call("state").getJSONObject("playback")
        check(opened.getDouble("rate") == 1.75 && !opened.getBoolean("playing")) { "Book did not restore desktop speed: $opened" }
        check(opened.getLong("position") == 90000L) { "Speed changed listening position: $opened" }
        suite.call("rate", "value" to 2.25)
        val changeDeadline = SystemClock.elapsedRealtime() + 10000
        while (suite.call("state").getJSONArray("book_rates").getJSONObject(0).getDouble("value") != 2.25 && SystemClock.elapsedRealtime() < changeDeadline) Thread.sleep(50)
        check(suite.call("state").getJSONArray("book_rates").getJSONObject(0).getDouble("value") == 2.25)
        check(suite.call("state").getJSONObject("playback").getLong("position") == 90000L)
        suite.note("Book speed received from desktop, restored by Android and changed without moving position")
        suite.call("sync_progress", "position" to 20000L)
        UiSuite(instrumentation).call("action", "name" to "sync-now")
        Thread.sleep(4500)
        suite.call("sync_reset")
        UiSuite(instrumentation).call("action", "name" to "sync-now")
        Thread.sleep(4500)
        check(suite.call("state").getJSONArray("progress").length() == 0)
        suite.note("Rewind and reset sent back to the desktop")
    }
}
